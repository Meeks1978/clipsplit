/**
 * UI data builder — regenerates ui/data.js (+ ui/data.json) for the demo UI.
 *
 * Pipeline: examples/sample-clips.json -> payout engine (real rules
 * dataset) -> PayoutLedger -> sandbox batch preview (src/paypal/
 * batchPreview.ts). The static page (ui/index.html) loads data.js and
 * renders it with AG Grid; no server, no fetch, no network calls are made
 * by the page itself (AG Grid loads from a CDN — see index.html note).
 *
 * Run:  npm run ui
 */

import { readFileSync, writeFileSync } from "node:fs";
import { CAMPAIGN_RULES, findCampaign } from "../src/data/campaigns.ts";
import { computePayoutLedger } from "../src/engine/payout.ts";
import { buildSandboxBatchPreview } from "../src/paypal/batchPreview.ts";
import type { ClipRecord } from "../src/types.ts";

const raw = JSON.parse(
  readFileSync(new URL("../examples/sample-clips.json", import.meta.url), "utf8"),
) as Array<Record<string, unknown>>;

const clips: ClipRecord[] = raw.map(
  ({ _comment, ...rest }) => rest as unknown as ClipRecord,
);

const ledger = computePayoutLedger(clips, CAMPAIGN_RULES);
const batchPreview = buildSandboxBatchPreview(ledger);

function gateStatus(campaignId: string, flags: string[]): string {
  if (flags.includes("GATE_MISSED")) return "Gate missed";
  if (flags.includes("GATE_DATA_MISSING")) return "Gate data missing";
  const rule = findCampaign(campaignId);
  if (rule && rule.gates.length > 0) return "Gates passed";
  return "No gates";
}

const ledgerRows = ledger.clips.map((p) => ({
  ...p,
  campaignName: findCampaign(p.campaignId)?.name ?? p.campaignId,
  gateStatus: gateStatus(p.campaignId, p.flags),
}));

const anomalies = ledger.clips
  .filter((p) => p.flags.length > 0)
  .map((p) => ({
    clipId: p.clipId,
    clipperId: p.clipperId,
    campaignName: findCampaign(p.campaignId)?.name ?? p.campaignId,
    flags: p.flags,
    explanation: p.notes.join(" "),
  }));

const data = {
  generatedAt: new Date().toISOString(),
  source: "examples/sample-clips.json priced by src/engine/payout.ts against src/data/campaigns.ts",
  campaignRules: CAMPAIGN_RULES.length,
  ledgerRows,
  perClipper: ledger.perClipper,
  totals: ledger.totals,
  anomalies,
  batchPreview,
};

const banner =
  "// GENERATED by ui/build-ui-data.ts (npm run ui) — do not edit by hand.\n" +
  "// Prices examples/sample-clips.json with the real payout engine. No network calls.\n";
writeFileSync(new URL("./data.js", import.meta.url), `${banner}window.CLIPSPLIT_DATA = ${JSON.stringify(data, null, 2)};\n`);
writeFileSync(new URL("./data.json", import.meta.url), `${JSON.stringify(data, null, 2)}\n`);

console.log(
  `ui/data.js written: ${ledger.totals.clipCount} clips, ` +
    `${ledger.totals.payableClipCount} payable, $${ledger.totals.totalPayoutUSD.toFixed(2)} total payout, ` +
    `${anomalies.length} anomalies, batch preview ${batchPreview.items.length} item(s) / ${batchPreview.skipped.length} skipped.`,
);
